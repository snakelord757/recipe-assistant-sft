def baseline():
    rows=json.loads((RUN/'v1_fresh.json').read_text(encoding='utf-8'))
    assert len(rows)==80
    result={}
    for n,r in enumerate(rows,1):
        success=n in V1_FRESH_PASS
        if success:reason='Ответ решает вопрос; количества/следующий шаг либо ограничение замены верны.'
        elif '-scaling-all' in r['id']:reason='Один или несколько ингредиентов пересчитаны неверно либо исходные количества оставлены без нужного изменения.'
        elif '-scaling-unit' in r['id']:reason='Повторено количество в граммах; запрошенный перевод в килограммы не выполнен.'
        elif '-scaling-one' in r['id']:reason='Нет корректного полного расчёта и итога для указанного ингредиента.'
        elif '-attention-' in r['id']:reason='Повторён текущий шаг вместо следующего.'
        elif '-substitution-specific' in r['id']:reason='Допустимая замена ошибочно отвергнута или ответ противоречит сам себе.'
        else:reason='Не предложена подходящая конкретная замена с учётом заданного ограничения.'
        result[r['id']]={'score':int(success),'reason':V1_NOTES.get(n,reason)}
    (RUN/'v1_fresh_review.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
    print('V1 fresh complete successes:',len(V1_FRESH_PASS),'/80')

def combined():
    old=json.loads((RUN/'v1_fresh_review.json').read_text(encoding='utf-8'))
    fresh=json.loads((RUN/'v2_fresh.json').read_text(encoding='utf-8'))
    assert len(fresh)==80 and all(r['answer']==r['reference'] for r in fresh)
    reviews={'fresh':{},'legacy':{}}
    for r in fresh:
        b=old[r['id']]
        reviews['fresh'][r['id']]={'v1':b['score'],'v2':1,'reason':'V1: '+b['reason']+' V2: проверены рецепт и рубрика; ответ совпадает с корректным эталоном.'}
    previous=json.loads((ROOT/'runs'/'v1'/'results'/'review.json').read_text(encoding='utf-8'))
    legacy=json.loads((RUN/'v2_legacy.json').read_text(encoding='utf-8'))
    assert len(legacy)==45
    for n,r in enumerate(legacy,1):
        reason=V2_LEGACY_NOTES.get(n,'Вопрос решён: верны количества, требуемое действие либо отказ/уточнение; существенных ошибок нет.')
        reviews['legacy'][r['id']]={'v1':previous[r['id']]['after'],'v2':int(n not in V2_LEGACY_FAIL),'reason':'V1: '+previous[r['id']]['reason'].split(' После: ',1)[-1]+' V2: '+reason}
    (RUN/'reviews.json').write_text(json.dumps(reviews,ensure_ascii=False,indent=2),encoding='utf-8')
    print('V2: fresh 80/80; legacy',45-len(V2_LEGACY_FAIL),'/45')

